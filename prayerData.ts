// Helper to format date as "DD/MM/YYYY"
export function formatDateKey(d: Date): string {
  const day = d.getDate().toString().padStart(2, "0");
  const month = (d.getMonth() + 1).toString().padStart(2, "0");
  const year = d.getFullYear();
  return `${day}/${month}/${year}`;
}

export function getPrayerScheduleForDate(d: Date): PrayerScheduleDay {
  const key = formatDateKey(d);
  const found = PRAYER_SCHEDULE_2026.find((item) => item.dateKey === key);
  if (found) return found;

  // Fallback if current system clock is on a different date: return 21/09/2026 or closest day
  return PRAYER_SCHEDULE_2026.find((item) => item.dateKey === "21/09/2026") || PRAYER_SCHEDULE_2026[0];
}

